/** 安装说明。只有最新版需要说得细一点，历史版本一句带过。 */
export function installHint(version) {
  const base = '`github:miaocell/magpie-doubao-work-auth'
  if (version === LATEST) {
    return `magpie 里添加供应商，来源填 ${base}#${version}\`，或直接用主分支 ${base}\`。`
  }
  return `magpie 里添加供应商，来源填 ${base}#${version}\`。`
}
